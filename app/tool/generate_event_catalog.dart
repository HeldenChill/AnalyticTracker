import 'dart:convert';
import 'dart:io';
import 'dart:typed_data';
import 'package:analytic_app/src/presentation/event_catalog.dart';
import 'package:analytic_app/src/presentation/event_catalog_import.dart';

void main(List<String> args) {
  final csv = Directory('../csv');
  final paths = csv
      .listSync()
      .whereType<File>()
      .where((f) => f.path.endsWith('.csv'))
      .toList()
    ..sort((a, b) => a.path.compareTo(b.path));
  final preview = previewVocabulary(files: [
    for (final f in paths)
      VocabularyFile(
          f.uri.pathSegments.last, Uint8List.fromList(f.readAsBytesSync()))
  ], current: EventCatalog({}), scope: 'baseline', baseRevision: 0);
  if (!preview.canApply) {
    stderr.writeln(preview.issues
        .map((i) => '${i.fileName}:${i.record} ${i.message}')
        .join('\n'));
    exitCode = 1;
    return;
  }
  final labels = objectMap(
      jsonDecode(File('../csv/event-labels.json').readAsStringSync()));
  if (labels['schemaVersion'] != 1) {
    throw const FormatException('Unsupported label schema');
  }
  final catalog = <String, EventMeaning>{};
  final eventLabels = objectMap(labels['events']);
  if (eventLabels.keys.any((k) => !preview.replacements.containsKey(k))) {
    throw const FormatException('Unknown reviewed alias');
  }
  for (final id in preview.replacements.keys.toList()..sort()) {
    final raw = preview.replacements[id]!;
    final override = objectMap(eventLabels[id]);
    final parameterLabels =
        objectMap(objectMap(labels['parameterLabels'])[id] ?? {});
    catalog[id] = EventMeaning(
        rawId: id,
        fullName: raw.fullName,
        label: requiredText(override, 'label'),
        description: override['description'] as String?,
        modeBTemplate: raw.modeBTemplate,
        sources: raw.sources,
        parameters: {
          for (final p
              in (raw.parameters.entries.toList()
                ..sort((a, b) => a.key.compareTo(b.key))))
            p.key: ParameterMeaning(
                fullName: p.value.fullName,
                label: parameterLabels[p.key] as String? ?? p.value.label,
                description: p.value.description)
        },
        tutorials: {
          for (final t
              in (raw.tutorials.entries.toList()
                ..sort((a, b) => a.key.compareTo(b.key))))
            t.key: TutorialMeaning(
                id: t.key,
                label: requiredText(
                    objectMap(objectMap(labels['tutorials'])[t.key]), 'label'),
                content: t.value.content)
        });
  }
  final encoded = jsonEncode(EventCatalog(catalog).toJson());
  // jsonEncode gives a valid quoted Dart literal after escaping interpolation.
  final literal = jsonEncode(encoded).replaceAll(r'$', r'\$');
  final generated =
      "// Generated by tool/generate_event_catalog.dart. Do not edit.\n"
      "import 'dart:convert';\nimport 'event_catalog.dart';\n\n"
      "const bundledCatalogJson = $literal;\n"
      "final bundledEventCatalog = EventCatalog.fromJson(objectMap(jsonDecode(bundledCatalogJson)));\n";
  final output = File('lib/src/presentation/event_catalog_data.dart');
  final report = StringBuffer('# Event vocabulary baseline coverage\n\n')
    ..writeln(
        '60 event aliases; 24 tutorial IDs. Source rows: Events 30, FTU 33, Tutorial 24.\n')
    ..writeln('| Source | Record | Raw ID | Reviewed label |')
    ..writeln('|---|---|---|---|');
  for (final e in catalog.values) {
    for (final source in e.sources) {
      report.writeln(
          '| ${source.fileName} | ${source.record} | ${e.rawId} | ${e.label} |');
    }
  }
  report.writeln('\n## Warnings and skipped rows\n');
  for (final i in preview.issues) {
    report.writeln('- ${i.fileName}:${i.record}: ${i.message}');
  }
  report.writeln(
      '\nTutorials Tut_17 through Tut_20 and Tut_opt_4 have undocumented content; preserve IDs and disclose unavailable meaning.');
  final reportFile =
      File('../.cursor/plans/event-vocabulary-baseline-coverage.md');
  if (args.contains('--check')) {
    if (!output.existsSync() ||
        output.readAsStringSync() != generated ||
        !reportFile.existsSync() ||
        reportFile.readAsStringSync() != report.toString()) {
      stderr.writeln('Generated vocabulary or coverage report is stale');
      exitCode = 1;
    }
  } else {
    output.writeAsStringSync(generated);
    reportFile.writeAsStringSync(report.toString());
  }
  stdout.writeln(
      'Validated ${catalog.length} aliases and ${catalog['tut']!.tutorials.length} tutorials.');
}
